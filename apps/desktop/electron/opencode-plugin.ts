/**
 * The opencode plugin Manor installs so an opencode pane gets an **Agent**.
 *
 * opencode has no hook config; it loads every `*.js`/`*.ts` file in
 * `<config>/plugins/` (`$XDG_CONFIG_HOME/opencode`, else `~/.config/opencode`)
 * as a plugin. Manor writes `manor-hooks.js` there, the way it writes pi's
 * extension: on every registration, only when its content changed. Outside a
 * Manor pane (no `MANOR_PANE_ID`) the plugin does nothing.
 *
 * Inside one, it turns opencode's bus events into the hook events the
 * Claude hook script sends (`agent-hook-events.ts`), for the root session
 * only (a subtask's session has a `parentID`):
 *
 * | opencode                                   | hook event          |
 * |--------------------------------------------|---------------------|
 * | `session.created`                          | `SessionStart`      |
 * | `session.status` busy/retry, from idle     | `UserPromptSubmit`  |
 * | `tool.execute.before`                      | `PreToolUse`        |
 * | `tool.execute.after`                       | `PostToolUse`       |
 * | `permission.asked`/`.updated`, `question.asked` | `PermissionRequest` |
 * | `permission.replied`, `question.replied`/`.rejected` | `PreToolUse` (the tool goes on) |
 * | `session.idle` / `session.status` idle, from busy | `Stop`       |
 * | `session.deleted`                          | `SessionEnd`        |
 *
 * Every event carries `transcriptPath = <opencode.db>#<sessionID>`
 * (`sessions/opencode-locator.ts`): opencode keeps no transcript file, so the
 * chat mirror reads the session's rows from its database
 * (`chat-mirror/opencode-db-source.ts`). The database path follows the rule
 * `sessions/opencode-reader.ts` `opencodeDbPath` documents, computed in the
 * plugin from opencode's own environment.
 */

import * as path from "node:path";

/** The plugin's file name in opencode's plugins directory. */
export const OPENCODE_PLUGIN_FILE = "manor-hooks.js";

/** opencode's global plugins directory, for `env` and `home`. */
export function opencodePluginsDir(env: NodeJS.ProcessEnv, home: string): string {
  const xdg = env.XDG_CONFIG_HOME?.trim();
  return path.join(xdg ? xdg : path.join(home, ".config"), "opencode", "plugins");
}

/** Separates the database path from the session id in an opencode transcript locator. */
const OPENCODE_LOCATOR_SEPARATOR = "#";

/** The plugin's source: an ES module whose one export is the plugin. */
export function opencodePluginSource(): string {
  return `/**
 * Manor hooks plugin for opencode: sends agent lifecycle events to Manor.
 * Auto-generated by Manor. Do not edit.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import * as os from "node:os";

const PANE_ID = process.env.MANOR_PANE_ID;
// A remote Manor daemon's panes name their own port file (port, then token).
const HOOK_PORT_FILE =
  process.env.MANOR_HOOK_PORT_FILE || path.join(process.env.HOME || os.homedir(), ".manor", "hook-port");

/** opencode's database: $OPENCODE_DB, else opencode.db in its data directory. */
function dbPath() {
  const home = process.env.HOME || os.homedir();
  const xdg = (process.env.XDG_DATA_HOME || "").trim();
  const dataDir = path.join(xdg || path.join(home, ".local", "share"), "opencode");
  const db = (process.env.OPENCODE_DB || "").trim();
  if (!db) return path.join(dataDir, "opencode.db");
  if (db === ":memory:") return null;
  return path.isAbsolute(db) ? db : path.resolve(dataDir, db);
}

function hookEndpoint() {
  try {
    const [portLine, tokenLine] = fs.readFileSync(HOOK_PORT_FILE, "utf-8").split("\\n");
    const port = portLine && portLine.trim();
    if (port) return { port, token: (tokenLine && tokenLine.trim()) || undefined };
  } catch {
    // No port file: the environment's, if any.
  }
  const port = process.env.MANOR_HOOK_PORT;
  return port ? { port, token: process.env.MANOR_HOOK_TOKEN || undefined } : null;
}

async function sendHook(eventType, sessionId, extra) {
  const endpoint = hookEndpoint();
  if (!endpoint) return;
  const url = new URL("http://127.0.0.1/hook/event");
  url.port = endpoint.port;
  url.searchParams.set("paneId", PANE_ID);
  url.searchParams.set("eventType", eventType);
  url.searchParams.set("kind", "opencode");
  url.searchParams.set("sessionId", sessionId);
  const db = dbPath();
  if (db) url.searchParams.set("transcriptPath", db + "${OPENCODE_LOCATOR_SEPARATOR}" + sessionId);
  for (const [key, value] of Object.entries(extra || {})) {
    if (value) url.searchParams.set(key, value);
  }
  try {
    await fetch(url.toString(), {
      method: "GET",
      ...(endpoint.token ? { headers: { "x-manor-hook-token": endpoint.token } } : {}),
      signal: AbortSignal.timeout(2000),
    });
  } catch {
    // Ignore errors: Manor might not be running.
  }
}

/** Tools whose file argument is the file they wrote. */
const WRITE_TOOLS = new Set(["edit", "write", "multiedit", "patch"]);

export const ManorHooks = async (ctx) => {
  if (!PANE_ID) return {};
  const client = ctx && ctx.client;
  /** Session id → whether it is a subtask's (has a parent). */
  const child = new Map();
  /** Root sessions with a turn in progress. */
  const busy = new Set();
  /** A write tool's file, by call id, from before it ran to after. */
  const files = new Map();

  async function isChild(sessionId) {
    if (child.has(sessionId)) return child.get(sessionId);
    let parent = false;
    try {
      const got = await client.session.get({ path: { id: sessionId } });
      parent = Boolean(got && got.data && got.data.parentID);
    } catch {
      // Unknown: taken as the root's.
    }
    child.set(sessionId, parent);
    return parent;
  }

  async function root(sessionId) {
    return typeof sessionId === "string" && sessionId !== "" && !(await isChild(sessionId));
  }

  async function turnStarted(sessionId) {
    if (busy.has(sessionId)) return;
    busy.add(sessionId);
    await sendHook("UserPromptSubmit", sessionId);
  }

  async function turnEnded(sessionId) {
    if (!busy.delete(sessionId)) return;
    await sendHook("Stop", sessionId);
  }

  return {
    event: async ({ event }) => {
      const type = event && event.type;
      const props = (event && event.properties) || {};
      if (type === "session.created" || type === "session.deleted") {
        const info = props.info || {};
        if (!info.id) return;
        child.set(info.id, Boolean(info.parentID));
        if (info.parentID) return;
        if (type === "session.created") await sendHook("SessionStart", info.id);
        else {
          busy.delete(info.id);
          await sendHook("SessionEnd", info.id);
        }
        return;
      }
      const sessionId = props.sessionID;
      if (!(await root(sessionId))) return;
      switch (type) {
        case "session.status": {
          const status = props.status && props.status.type;
          if (status === "busy" || status === "retry") await turnStarted(sessionId);
          else if (status === "idle") await turnEnded(sessionId);
          return;
        }
        case "session.idle":
          await turnEnded(sessionId);
          return;
        case "permission.asked":
        case "permission.updated":
        case "question.asked":
          await sendHook("PermissionRequest", sessionId);
          return;
        case "permission.replied":
        case "question.replied":
        case "question.rejected":
          await sendHook("PreToolUse", sessionId);
          return;
      }
    },
    "tool.execute.before": async (input, output) => {
      if (!input || !(await root(input.sessionID))) return;
      const args = (output && output.args) || {};
      const file = args.filePath || args.file_path;
      if (WRITE_TOOLS.has(input.tool) && typeof file === "string" && input.callID) {
        files.set(input.callID, file);
      }
      await sendHook("PreToolUse", input.sessionID);
    },
    "tool.execute.after": async (input) => {
      if (!input || !(await root(input.sessionID))) return;
      const file = files.get(input.callID);
      files.delete(input.callID);
      await sendHook("PostToolUse", input.sessionID, { filePath: file });
    },
  };
};
`;
}
