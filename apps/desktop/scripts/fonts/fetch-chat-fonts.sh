#!/usr/bin/env bash
# Regenerates public/fonts/chat/ and src/chat-fonts.css: the fonts chat can be
# drawn in (Settings › Font). Each is a variable font from Fontsource, cut to
# Latin and Latin Extended, under the SIL Open Font License shipped beside it.
# Picked by name in src/lib/chat-fonts.ts.
set -euo pipefail

VERSION=5.3.0
FONTS=(
  "inter|Inter"
  "literata|Literata"
  "atkinson-hyperlegible-next|Atkinson Hyperlegible Next"
  "ibm-plex-sans|IBM Plex Sans"
  "jetbrains-mono|JetBrains Mono"
)

here="$(cd "$(dirname "$0")" && pwd)"
desktop="$here/../.."
out="$desktop/public/fonts/chat"
css="$desktop/src/chat-fonts.css"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

rm -rf "$out"
mkdir -p "$out"
cat > "$css" <<'CSS'
/*
 * The fonts chat can be drawn in (`lib/chat-fonts`), generated by
 * `scripts/fonts/fetch-chat-fonts.sh`. A browser downloads a file only when
 * text on screen uses that family, style and range.
 */
CSS

for entry in "${FONTS[@]}"; do
  slug="${entry%%|*}"
  name="${entry##*|}"
  (cd "$work" && npm pack --silent "@fontsource-variable/$slug@$VERSION" >/dev/null)
  mkdir -p "$work/$slug"
  tar xzf "$work/fontsource-variable-$slug-$VERSION.tgz" -C "$work/$slug"
  pkg="$work/$slug/package"
  cp "$pkg/LICENSE" "$out/$slug-LICENSE.txt"
  for style in normal italic; do
    for subset in latin latin-ext; do
      cp "$pkg/files/$slug-$subset-wght-$style.woff2" "$out/"
    done
  done
  python3 -I - "$pkg" "$slug" "$name" >> "$css" <<'PY'
import re, sys
pkg, slug, name = sys.argv[1:]
for sheet in ("wght.css", "wght-italic.css"):
    text = open(f"{pkg}/{sheet}").read()
    for comment, rule in re.findall(r"/\* (\S+) \*/\s*(@font-face \{.*?\})", text, re.S):
        if not re.fullmatch(rf"{re.escape(slug)}-latin(-ext)?-wght-(normal|italic)", comment):
            continue
        rule = re.sub(r"font-family: *'[^']*'", f'font-family: "{name}"', rule)
        rule = re.sub(r"url\(\./files/", "url(/fonts/chat/", rule)
        print(rule)
PY
done
