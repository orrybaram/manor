/**
 * The `kubernetes` template (ADR-229 D8): a StatefulSet of one with a
 * volume claim for the home directory and a Secret holding the key that
 * seals the host's secrets (D5), reached over `kubectl exec -i`. `stop`
 * scales it to 0, `up` to 1, `destroy` deletes the set, the claim and the
 * Secret.
 *
 * The scripts keep stdout for the one JSON object (fd 3).
 */

import type { Recipe } from "../recipes";
import {
  answer,
  defaultHostImage,
  CONTEXT_PATTERN,
  IMAGE_PATTERN,
  NAME_PATTERN,
  shortName,
  type RecipeTemplate,
} from "./types";

const UP = `#!/usr/bin/env bash
# Generated by Manor from the "kubernetes" template. Edit freely: this recipe is yours.
# Stdout is reserved for the one JSON result; everything else goes to stderr.
set -euo pipefail
exec 3>&1 1>&2

if ! command -v kubectl >/dev/null 2>&1; then
  echo "manor: kubectl was not found on PATH; install it and try again" >&2
  exit 1
fi

name=\${MANOR_K8S_NAME:?MANOR_K8S_NAME is not set}
namespace=\${MANOR_K8S_NAMESPACE:?MANOR_K8S_NAMESPACE is not set}
kubectl_cmd=(kubectl)
if [ -n "\${MANOR_K8S_CONTEXT:-}" ]; then
  kubectl_cmd+=(--context "$MANOR_K8S_CONTEXT")
fi
kube=("\${kubectl_cmd[@]}" -n "$namespace")
image=\${MANOR_K8S_IMAGE:?MANOR_K8S_IMAGE is not set}
storage=\${MANOR_K8S_STORAGE:-20Gi}
storage_class_line=""
if [ -n "\${MANOR_K8S_STORAGE_CLASS:-}" ]; then
  storage_class_line="storageClassName: $MANOR_K8S_STORAGE_CLASS"
fi
# What the pod asks for (the size picked in the form). A recipe made before
# sizes existed has none, and the pod asks for nothing.
resources_block=""
if [ -n "\${MANOR_K8S_CPU:-}" ] && [ -n "\${MANOR_K8S_MEMORY:-}" ]; then
  resources_block="resources:
            requests:
              cpu: \\"$MANOR_K8S_CPU\\"
              memory: \\"$MANOR_K8S_MEMORY\\"
            limits:
              memory: \\"$MANOR_K8S_MEMORY\\""
fi

# The namespace is Manor's to create when it is missing.
if ! "\${kubectl_cmd[@]}" get namespace "$namespace" >/dev/null 2>&1; then
  echo "Creating namespace $namespace"
  "\${kubectl_cmd[@]}" create namespace "$namespace"
fi

# The key that seals the host's secrets (ADR-229 D5), generated once. A Secret
# is not on the home volume, so a copy of the volume cannot read them.
if ! "\${kube[@]}" get secret "$name-key" >/dev/null 2>&1; then
  echo "Generating secret $name-key"
  key=$(head -c 32 /dev/urandom | base64 | tr -d '\\n')
  "\${kube[@]}" apply -f - <<YAML
apiVersion: v1
kind: Secret
metadata:
  name: $name-key
type: Opaque
data:
  key: $key
YAML
fi

# One replica, with a volume claim for the home directory.
"\${kube[@]}" apply -f - <<YAML
apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: $name
spec:
  serviceName: $name
  replicas: 1
  selector:
    matchLabels:
      app: $name
  template:
    metadata:
      labels:
        app: $name
    spec:
      securityContext:
        runAsNonRoot: true
        runAsUser: 1000
        runAsGroup: 1000
        fsGroup: 1000
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: host
          image: $image
          securityContext:
            allowPrivilegeEscalation: false
            capabilities:
              drop: ["ALL"]
          $resources_block
          env:
            - name: MANOR_SECRET_KEY_FILE
              value: /run/secrets/manor-key
            - name: MANOR_INSTANCE_ID
              value: "$namespace/$name"
          volumeMounts:
            - name: home
              mountPath: /home/manor
            - name: key
              mountPath: /run/secrets/manor-key
              subPath: key
              readOnly: true
      volumes:
        - name: key
          secret:
            secretName: $name-key
            defaultMode: 0440
  volumeClaimTemplates:
    - metadata:
        name: home
      spec:
        accessModes: ["ReadWriteOnce"]
        $storage_class_line
        resources:
          requests:
            storage: $storage
YAML

"\${kube[@]}" scale statefulset "$name" --replicas=1
"\${kube[@]}" rollout status statefulset "$name" --timeout=10m

# No-op examples of the hooks the host runs when it turns busy or idle
# (ADR-229 D7). Written only if absent: they are yours to edit.
"\${kube[@]}" exec -i "$name-0" -c host -- sh -s <<'HOOKS'
set -eu
hooks="$HOME/.manor/remote/hooks"
mkdir -p "$hooks"
for hook in on-idle on-busy; do
  if [ ! -e "$hooks/$hook" ]; then
    printf '#!/bin/sh\\n# %s: Manor runs this when the host turns %s (ADR-229 D7).\\nexit 0\\n' "$hook" "\${hook#on-}" >"$hooks/$hook"
    chmod 755 "$hooks/$hook"
  fi
done
HOOKS

argv='"kubectl"'
if [ -n "\${MANOR_K8S_CONTEXT:-}" ]; then
  argv="$argv,\\"--context\\",\\"$MANOR_K8S_CONTEXT\\""
fi
printf '{"schemaVersion":1,"resource":{"namespace":"%s","name":"%s"},"connection":{"type":"exec","argv":[%s,"-n","%s","exec","-i","%s-0","-c","host","--"]}}\\n' \\
  "$namespace" "$name" "$argv" "$namespace" "$name" >&3
`;

const STATUS = `#!/usr/bin/env bash
# Generated by Manor from the "kubernetes" template. Edit freely: this recipe is yours.
# Stdout is reserved for the one JSON result; everything else goes to stderr.
set -euo pipefail
exec 3>&1 1>&2

if ! command -v kubectl >/dev/null 2>&1; then
  echo "manor: kubectl was not found on PATH; install it and try again" >&2
  exit 1
fi

name=\${MANOR_K8S_NAME:?MANOR_K8S_NAME is not set}
namespace=\${MANOR_K8S_NAMESPACE:?MANOR_K8S_NAMESPACE is not set}
kubectl_cmd=(kubectl)
if [ -n "\${MANOR_K8S_CONTEXT:-}" ]; then
  kubectl_cmd+=(--context "$MANOR_K8S_CONTEXT")
fi
kube=("\${kubectl_cmd[@]}" -n "$namespace")

if ! out=$("\${kube[@]}" get statefulset "$name" -o 'jsonpath={.spec.replicas}' 2>&1); then
  echo "$out" >&2
  case "$out" in
    *NotFound* | *"not found"*) echo '{"state":"missing"}' >&3 ;;
    *) echo '{"state":"error","detail":"kubectl could not read the StatefulSet"}' >&3 ;;
  esac
  exit 0
fi
if [ "\${out:-0}" = "0" ]; then
  echo '{"state":"sleeping"}' >&3
  exit 0
fi
# Scaled up but not Ready is a pod being (re)started: deleted, evicted or
# rescheduled. It comes back by itself, so it is up; "sleeping" would stop
# Manor reconnecting to it (ADR-231 C1).
ready=$("\${kube[@]}" get pod "$name-0" -o 'jsonpath={.status.conditions[?(@.type=="Ready")].status}' 2>/dev/null || true)
if [ "$ready" = "True" ]; then
  echo '{"state":"up"}' >&3
else
  echo '{"state":"up","detail":"the pod is not ready yet"}' >&3
fi
`;

